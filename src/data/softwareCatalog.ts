export const matchProduct = (product: SoftwareProduct, industry: string, priorities: string[]) => {
  const industryOk =
    industry === 'all' ||
    product.industries.includes('all') ||
    product.industries.includes(industry);
  const covered = priorities.filter((p) => product.tags.includes(p));
  return { industryOk, covered };
};

